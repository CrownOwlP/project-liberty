#!/usr/bin/env node
/* ---------------------------------------------------------------------------
 * Product readiness, rendered from control/product-readiness.json (PW phase).
 *
 * WHY THIS IS A SEPARATE VIEW FROM `ai:status`, AND MUST STAY ONE.
 * `coordination/PROJECT_STATUS.md` reports DONE over the task board. That is a
 * true answer to "has the board been worked" and a MISLEADING answer to "can a
 * person install this and watch something": on the tree this file was written
 * against those two figures were 97% and roughly a third. A single number that
 * had to mean both would have to lie about one of them.
 *
 * WHY IT DOES NOT COUNT TASKS. A task count measures how work was CHOPPED UP.
 * Twenty tasks for the installer and one for native playback would make the
 * installer look like the product. So the unit here is a CAPABILITY a user
 * would notice, scored against the repository, with its evidence path beside
 * it -- and the checklist is printed in full, so the figure can always be
 * checked by opening the files it names rather than trusted.
 * ------------------------------------------------------------------------- */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const doc = JSON.parse(
  fs.readFileSync(path.join(root, "control", "product-readiness.json"), "utf8")
);

const SCORE = { present: 1, partial: 0.5, absent: 0 };
const MARK = { present: "[x]", partial: "[~]", absent: "[ ]" };

const problems = [];
for (const dimension of doc.dimensions) {
  if (!doc.weights[dimension.id]) problems.push(`${dimension.id}: no weight`);
  for (const item of dimension.items) {
    if (!(item.state in SCORE)) problems.push(`${dimension.id}/${item.id}: unknown state ${item.state}`);
    /* An item with no evidence is a defect in the data file, not a rounding
     * error: the whole claim of this view is that every figure is checkable. */
    if (!item.evidence) problems.push(`${dimension.id}/${item.id}: no evidence`);
  }
}
if (problems.length) {
  for (const problem of problems) console.error(`ERROR: ${problem}`);
  process.exit(1);
}

const scored = doc.dimensions.map((dimension) => {
  const total = dimension.items.length;
  const sum = dimension.items.reduce((acc, item) => acc + SCORE[item.state], 0);
  const counts = { present: 0, partial: 0, absent: 0 };
  for (const item of dimension.items) counts[item.state] += 1;
  return { ...dimension, total, sum, counts, weight: doc.weights[dimension.id], ratio: sum / total };
});

const weightTotal = scored.reduce((acc, d) => acc + d.weight, 0);
const overall = scored.reduce((acc, d) => acc + d.ratio * d.weight, 0) / weightTotal;
const pct = (value) => `${Math.round(value * 100)}%`;

const lines = [
  "# Project Liberty — product readiness",
  "",
  "> Generated by `node scripts/product-readiness.mjs` from",
  "> `control/product-readiness.json`. Do not edit this file; edit the data.",
  "",
  "**This is not the engineering completion figure and must never be compared to",
  "it.** `coordination/PROJECT_STATUS.md` answers *has the board been worked*.",
  "This answers *can a person install this on a Windows PC and watch something*.",
  "",
  `## Overall usable-product readiness: ${pct(overall)}`,
  "",
  "Weighted mean of the dimensions below, using the weights in the data file —",
  "not a mean of means, because the dimensions are not equally load-bearing.",
  "",
  "| Dimension | Readiness | Weight | present | partial | absent |",
  "| --- | --- | --- | --- | --- | --- |",
  ...scored.map(
    (d) =>
      `| ${d.title} | **${pct(d.ratio)}** | ${d.weight} | ${d.counts.present} | ${d.counts.partial} | ${d.counts.absent} |`
  ),
  "",
  "## How each figure is derived",
  "",
  "A capability scores `present` (1.0) when it is implemented **and reachable by",
  "a user of the shipped application**, `partial` (0.5) when it is implemented",
  "behind a seam a user cannot reach or for a target that is not the shipped one,",
  "and `absent` (0.0) when there is no implementation. A dimension's figure is",
  "the sum of its item scores over its item count.",
  "",
  "`partial` is doing real work here and is not a hedge. Profiles, watchlist and",
  "progress each have a complete, tested, reviewed HTTP API and no user interface",
  "at all. Scoring them absent would erase reviewed work; scoring them present",
  "would claim a person can use them.",
  ""
];

for (const dimension of scored) {
  lines.push(
    `### ${dimension.title} — ${pct(dimension.ratio)}`,
    "",
    `${dimension.sum} of ${dimension.total} capability points.`,
    ""
  );
  for (const item of dimension.items) {
    lines.push(`- ${MARK[item.state]} **${item.id}** — ${item.note}`);
    lines.push(`  - evidence: \`${item.evidence}\``);
  }
  lines.push("");
}

lines.push(
  "## What this view cannot tell you",
  "",
  "It scores what the repository contains, so it cannot distinguish code that",
  "compiles from code that works on a real Windows machine. Every item in",
  "**Windows desktop**, **Native playback** and **Packaging and release** will",
  "still need real-device evidence after it scores `present` here; that evidence",
  "is the Windows reliability certification track's job, and it is tracked",
  "separately in `docs/TEST_MATRIX.md` rather than being folded into this number.",
  ""
);

const out = path.join(root, "coordination", "PRODUCT_READINESS.md");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Product readiness: ${pct(overall)} overall`);
for (const d of scored) console.log(`  ${d.title.padEnd(32)} ${pct(d.ratio).padStart(4)}  (weight ${d.weight})`);
console.log(`Wrote ${path.relative(root, out)}`);
